-- =============================================================================
-- AMC CoopMart: schema (Oracle Database 19c and later)
-- 21 tables in six modules. Run this file first, then 02_sample_data.sql.
--
-- Tables are created in four phases so every foreign key points at a table
-- that already exists (the order used in the project documentation).
--
-- Two fixes against the documentation:
--   * MEMBER gains acquisition_details, which the data dictionary and the
--     INSERT statements use but the original CREATE TABLE left out.
--   * COURIER_PARTNER is created before SHIPMENT_TRACKING, which references it.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Phase 1: independent tables (no foreign keys)
-- -----------------------------------------------------------------------------

-- Membership module
CREATE TABLE MEMBERSHIP_TIER (
    tier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tier_name VARCHAR2(50) NOT NULL,
    annual_fee NUMBER(10,2) NOT NULL,
    discount_percentage NUMBER(5,2) NOT NULL
);

-- Marketing module
CREATE TABLE ACQUISITION_PLATFORM (
    platform_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_name VARCHAR2(100) NOT NULL,
    details VARCHAR2(4000)
);

-- Marketing module
CREATE TABLE MARKETING_CAMPAIGN (
    campaign_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_name VARCHAR2(120) NOT NULL,
    total_budget NUMBER(12,2) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL
);

-- Payment & Logistics module
CREATE TABLE PRODUCT (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(120) NOT NULL,
    description VARCHAR2(4000),
    price NUMBER(10,2) NOT NULL,
    stock_quantity NUMBER NOT NULL,
    unit_of_measure VARCHAR2(20) NOT NULL,
    category VARCHAR2(80) NOT NULL,
    reorder_level NUMBER NOT NULL
);

-- Payment & Logistics module
CREATE TABLE SUPPLIER (
    supplier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR2(150) NOT NULL,
    location VARCHAR2(150),
    contact_info VARCHAR2(150) UNIQUE
);

-- Payment & Logistics module
CREATE TABLE COURIER_PARTNER (
    courier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR2(120) NOT NULL,
    service_type VARCHAR2(80) NOT NULL,
    contact_info VARCHAR2(120)
);

-- Cooperative Engagement module
CREATE TABLE VOTING_EVENT (
    vote_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(150) NOT NULL,
    description VARCHAR2(4000),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_by_admin NUMBER NOT NULL
);


-- -----------------------------------------------------------------------------
-- Phase 2: first-level dependencies
-- -----------------------------------------------------------------------------

-- Membership module
CREATE TABLE MEMBER (
    member_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(120) NOT NULL,
    phone_number VARCHAR2(20) UNIQUE,
    address VARCHAR2(4000),
    join_date DATE DEFAULT SYSDATE NOT NULL,
    acquisition_platform_id NUMBER,
    acquisition_details VARCHAR2(4000),
    is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
    CONSTRAINT fk_member_platform FOREIGN KEY (acquisition_platform_id)
        REFERENCES ACQUISITION_PLATFORM(platform_id)
);

-- Marketing module
CREATE TABLE CAMPAIGN_PLATFORM_PERFORMANCE (
    performance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id NUMBER NOT NULL,
    platform_name VARCHAR2(100) NOT NULL,
    impressions_count NUMBER NOT NULL,
    clicks_count NUMBER NOT NULL,
    spend_on_platform NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_perf_campaign FOREIGN KEY (campaign_id)
        REFERENCES MARKETING_CAMPAIGN(campaign_id)
);

-- Payment & Logistics module
CREATE TABLE PRODUCT_SUPPLIER (
    product_id NUMBER NOT NULL,
    supplier_id NUMBER NOT NULL,
    cost_price NUMBER(10,2) NOT NULL,
    PRIMARY KEY (product_id, supplier_id),
    CONSTRAINT fk_ps_product FOREIGN KEY (product_id)
        REFERENCES PRODUCT(product_id),
    CONSTRAINT fk_ps_supplier FOREIGN KEY (supplier_id)
        REFERENCES SUPPLIER(supplier_id)
);


-- -----------------------------------------------------------------------------
-- Phase 3: second-level dependencies (mostly tables owned by a member)
-- -----------------------------------------------------------------------------

-- Membership module
CREATE TABLE MEMBERSHIP_SUBSCRIPTION (
    subscription_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    tier_id NUMBER NOT NULL,
    status VARCHAR2(30) NOT NULL,
    start_date DATE NOT NULL,
    expiry_date DATE NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
    CONSTRAINT fk_sub_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id),
    CONSTRAINT fk_sub_tier FOREIGN KEY (tier_id)
        REFERENCES MEMBERSHIP_TIER(tier_id)
);

-- Payment & Logistics module
CREATE TABLE SHOP_ORDER (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    order_placed_at TIMESTAMP NOT NULL,
    subtotal_amount NUMBER(12,2) NOT NULL,
    discount_applied NUMBER(12,2) NOT NULL,
    final_total_applied NUMBER(12,2) NOT NULL,
    order_status VARCHAR2(50) NOT NULL,
    fulfillment_type VARCHAR2(50) NOT NULL,
    pickup_store_id NUMBER,
    delivery_address VARCHAR2(4000),
    CONSTRAINT fk_order_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id)
);

-- Cooperative Engagement module
CREATE TABLE PRODUCT_SUGGESTION (
    suggestion_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    product_name VARCHAR2(120) NOT NULL,
    description VARCHAR2(4000),
    status VARCHAR2(50) NOT NULL,
    date_submitted DATE NOT NULL,
    supply_status VARCHAR2(50),
    CONSTRAINT fk_suggestion_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id)
);

-- Cooperative Engagement module
CREATE TABLE VOTE_CAST (
    vote_cast_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vote_id NUMBER NOT NULL,
    member_id NUMBER NOT NULL,
    choice VARCHAR2(50) NOT NULL,
    date_voted TIMESTAMP NOT NULL,
    CONSTRAINT fk_vote_event FOREIGN KEY (vote_id)
        REFERENCES VOTING_EVENT(vote_id),
    CONSTRAINT fk_vote_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id)
);

-- Cooperative Financials module
CREATE TABLE SHARE_CAPITAL_ACCOUNT (
    account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL UNIQUE,
    share_capital_balance NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_account_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id)
);

-- Cooperative Financials module
CREATE TABLE SHARE_CAPITAL_TRANSACTION (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    transaction_date DATE NOT NULL,
    transaction_type VARCHAR2(50) NOT NULL,
    amount NUMBER(12,2) NOT NULL,
    running_balance NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_transaction_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id)
);

-- Cooperative Financials module
CREATE TABLE COOP_DIVIDEND_PAYOUT (
    payout_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    fiscal_year NUMBER(4) NOT NULL,
    payout_date DATE NOT NULL,
    total_payout_amount NUMBER(12,2) NOT NULL,
    payout_breakdown_notes VARCHAR2(4000),
    CONSTRAINT fk_dividend_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id)
);


-- -----------------------------------------------------------------------------
-- Phase 4: final dependencies (order details and support)
-- -----------------------------------------------------------------------------

-- Payment & Logistics module
CREATE TABLE ORDER_ITEM (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity NUMBER NOT NULL,
    unit_price NUMBER(10,2) NOT NULL,
    line_total NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_orderitem_order FOREIGN KEY (order_id)
        REFERENCES SHOP_ORDER(order_id),
    CONSTRAINT fk_orderitem_product FOREIGN KEY (product_id)
        REFERENCES PRODUCT(product_id)
);

-- Payment & Logistics module
CREATE TABLE PAYMENT_RECORD (
    payment_id VARCHAR2(20) PRIMARY KEY,
    order_id NUMBER NOT NULL,
    payment_method VARCHAR2(50) NOT NULL,
    gateway_transaction_ref VARCHAR2(150) UNIQUE,
    payment_confirmed_at TIMESTAMP,
    status VARCHAR2(40) NOT NULL,
    CONSTRAINT fk_pay_order FOREIGN KEY (order_id)
        REFERENCES SHOP_ORDER(order_id)
);

-- Payment & Logistics module
CREATE TABLE SHIPMENT_TRACKING (
    shipment_id VARCHAR2(30) PRIMARY KEY,
    order_id NUMBER NOT NULL,
    courier_id NUMBER NOT NULL,
    tracking_number VARCHAR2(120),
    dispatched_at TIMESTAMP,
    delivered_at TIMESTAMP,
    shipment_status VARCHAR2(50) NOT NULL,
    CONSTRAINT fk_shipment_order FOREIGN KEY (order_id)
        REFERENCES SHOP_ORDER(order_id),
    CONSTRAINT fk_shipment_courier FOREIGN KEY (courier_id)
        REFERENCES COURIER_PARTNER(courier_id)
);

-- CRM module
CREATE TABLE CRM_SUPPORT_TICKET (
    ticket_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    order_id NUMBER,
    issue_category VARCHAR2(80) NOT NULL,
    priority VARCHAR2(20) NOT NULL,
    status VARCHAR2(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP,
    details VARCHAR2(4000),
    CONSTRAINT fk_ticket_member FOREIGN KEY (member_id)
        REFERENCES MEMBER(member_id),
    CONSTRAINT fk_ticket_order FOREIGN KEY (order_id)
        REFERENCES SHOP_ORDER(order_id)
);
