-- TABLE: an audit log of order changes
CREATE TABLE order_audit_log (
    log_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     NUMBER NOT NULL,
    action_taken VARCHAR2(100) NOT NULL,
    action_date  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- VIEW: orders and spending per member
CREATE VIEW member_order_summary AS
SELECT m.member_id,
       m.full_name,
       COUNT(o.order_id)          AS total_orders,
       SUM(o.final_total_applied) AS total_spent
FROM   member m
       JOIN shop_order o ON m.member_id = o.member_id
GROUP  BY m.member_id, m.full_name;

-- SEQUENCE: running numbers, for example for support logs
CREATE SEQUENCE seq_support_log START WITH 1 INCREMENT BY 1;

-- INDEX: faster searches of orders by status
CREATE INDEX idx_shop_order_status ON shop_order(order_status);

-- SYNONYM: a shorter name for shop_order
CREATE SYNONYM orders FOR shop_order;

-- Try them
